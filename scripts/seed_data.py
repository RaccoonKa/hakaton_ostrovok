def validate_datasets():
    """Валидация бизнес-правил и структуры данных."""
    print("Проверка 1: Направления...")
    assert len(DESTINATIONS) == 5, f"Ожидалось 5 направлений, получено {len(DESTINATIONS)}"
    dest_cities = {d["city"] for d in DESTINATIONS}
    expected_cities = {"Сочи", "Калининград", "Санкт-Петербург", "Стамбул", "Анталья"}
    assert dest_cities == expected_cities, f"Города не совпадают: {dest_cities} != {expected_cities}"

    print("Проверка 2: Отели (количество и требования к собакам)...")
    assert len(HOTELS) >= 25, f"Ожидалось не менее 25 отелей, получено {len(HOTELS)}"
    
    hotels_by_city: dict[str, list[dict]] = {}
    for h in HOTELS:
        city = h["city"]
        hotels_by_city.setdefault(city, []).append(h)

    for city in expected_cities:
        city_hotels = hotels_by_city.get(city, [])
        assert len(city_hotels) >= 4, f"В городе {city} мало отелей: {len(city_hotels)}"
        pet_hotels = [h for h in city_hotels if h.get("pet_friendly")]
        assert len(pet_hotels) >= 1, f"В городе {city} НЕТ отелей pet_friendly!"
        for ph in pet_hotels:
            assert ph.get("pet_fee_per_night", 0) > 0, f"У pet_friendly отеля {ph['hotel']} не указан pet_fee_per_night"

    # Проверка All Inclusive
    all_inc_hotels = [h for h in HOTELS if h.get("meal_plan") == "all_inclusive"]
    assert any(h["hotel"].startswith("Bridge Resort") for h in all_inc_hotels), "Bridge Resort должен быть all_inclusive"
    assert any(h["city"] == "Анталья" for h in all_inc_hotels), "В Анталье должны быть отели all_inclusive"

    # Проверка невозвратных тарифов
    non_ref_hotels = [h for h in HOTELS if h.get("free_cancellation") is False]
    assert len(non_ref_hotels) >= 3, "Должно быть минимум 3 отеля с невозвратными тарифами"
    for nrh in non_ref_hotels:
        assert nrh.get("non_refundable_discount_pct", 0) > 0, f"Отель {nrh['hotel']} без скидки за невозвратность"

    print("Проверка 3: Рейсы (DP 115 кейс-ловушка и регулярные рейсы)...")
    assert any(f["flight_number"] == "DP 115" for f in FLIGHTS), "Рейс DP 115 отсутствует"
    dp115 = next(f for f in FLIGHTS if f["flight_number"] == "DP 115")
    assert dp115["arrival_time"] == "05:15", f"Прилет DP 115 должен быть в 05:15, а не {dp115['arrival_time']}"
    assert any(f["flight_number"] == "SU 1122" for f in FLIGHTS), "Рейс SU 1122 отсутствует"
    assert any(f["flight_number"] == "S7 2045" for f in FLIGHTS), "Рейс S7 2045 отсутствует"

    print("Проверка 4: Поезда (104В/103В и Сапсаны)...")
    train_numbers = {t["train_number"] for t in TRAINS}
    for req_train in ["104В", "103В", "772А", "771А"]:
        assert req_train in train_numbers, f"Поезд {req_train} отсутствует"

    print("Проверка 5: Трансферы и кейс «Трансфер съедает выгоду»...")
    hubs = {t["hub_id"] for t in TRANSFERS}
    req_hubs = {"AER", "ADLER_STATION", "SOCHI_STATION", "KGD", "LED", "MOSCOW_STATION_SPB", "IST", "AYT"}
    assert req_hubs.issubset(hubs), f"Не все хабы покрыты: {req_hubs - hubs}"

    # Проверка совместимости с Pydantic моделями domain
    print("Проверка 6: Валидация Pydantic domain models...")
