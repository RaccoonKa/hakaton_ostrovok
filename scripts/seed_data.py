def save_json(file_path: Path, data):
    """Сохранение данных в JSON с форматированием UTF-8."""
    with open(file_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"Сохранен: {file_path} ({len(data)} записей, {file_path.stat().st_size} байт)")


def main():
    DATA_DIR.mkdir(parents=True, exist_ok=True)

    validate_datasets()

    print("\nЗапись файлов в папку data/...")
    save_json(DATA_DIR / "destinations.json", DESTINATIONS)
    save_json(DATA_DIR / "hotels.json", HOTELS)
    save_json(DATA_DIR / "flights.json", FLIGHTS)
    save_json(DATA_DIR / "trains.json", TRAINS)
    save_json(DATA_DIR / "transfers.json", TRANSFERS)

